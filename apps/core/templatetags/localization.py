register = template.Library()


def _is_bad_demo_translation(value):
    text = str(value or "").strip()
    bad_prefixes = ("ترجمة:", "Translation:", "翻译:")
    return any(text.startswith(prefix) for prefix in bad_prefixes)


def _lookup(obj, field_name):
    if obj is None:
        return ""
    lang = get_language() or "en"
    content_type = obj.__class__.__name__.lower()
    object_id = getattr(obj, "id", None)
    fallback = getattr(obj, field_name, "")
    if not object_id or lang == "en":
        return fallback
    override = LocalizedContent.objects.filter(
        content_type=content_type,
        object_id=object_id,
        language_code=lang,
        field_name=field_name,
    ).first()
    fallback_map = globals().get("VISIBLE_CMS_FALLBACK_TRANSLATIONS", {}).get(lang, {})
    if override and override.text and not _is_bad_demo_translation(override.text):
        override_text = str(override.text).strip()
        # If an older seed stored an exact English copy as the localized value,
        # prefer the visible runtime translation instead of showing English on /ar/ or /zh-hans/.
        if fallback in fallback_map and override_text == str(fallback).strip():
            return fallback_map[fallback]
        return override.text
    if fallback in fallback_map:
        return fallback_map[fallback]
    # Many rich-text CMS fields store the English source wrapped in simple HTML
    # such as <p>...</p>. Match the visible text so Arabic/Chinese fallbacks
    # still display instead of English paragraphs.
    try:
        from django.utils.html import strip_tags
        raw_fallback = str(fallback or "")
        plain_fallback = " ".join(strip_tags(raw_fallback).split())
        if plain_fallback in fallback_map:
            translated = fallback_map[plain_fallback]
            if raw_fallback.strip().startswith("<"):
                return f"<p>{translated}</p>"
            return translated
    except Exception:
        pass
    return fallback


@register.simple_tag
def localized(obj, field_name):
    return mark_safe(_lookup(obj, field_name))


@register.simple_tag
def localized_plain(obj, field_name):
    value = _lookup(obj, field_name)
    return str(value)


@register.simple_tag
def localized_meta(obj, field_name, fallback=""):
    value = _lookup(obj, field_name)
    return str(value or fallback or "")




@register.simple_tag
def localized_lines(obj, field_name):
    """Return localized multi-line field as a clean list for templates."""
    value = _lookup(obj, field_name)
    return [line.strip() for line in str(value or "").splitlines() if line.strip()]

@register.simple_tag(takes_context=True)
def localized_url(context, url):
    """Keep internal links inside the current language prefix."""
    if not url:
        return "#"

    value = str(url)

    # External, mail, tel, anchors should not be changed.
    if value.startswith(("http://", "https://", "mailto:", "tel:", "#")):
        return value

    request = context.get("request")
    lang = get_language() or "en"

    if not value.startswith("/"):
        value = "/" + value

    # Remove existing language prefix first, then add current language if needed.
    for prefix in ["/ar", "/zh-hans", "/en"]:
        if value == prefix:
            value = "/"
            break
        if value.startswith(prefix + "/"):
            value = value[len(prefix):] or "/"
            break

    if lang == "ar":
        return "/ar" + value if value != "/" else "/ar/"
    if lang == "zh-hans":
        return "/zh-hans" + value if value != "/" else "/zh-hans/"
    return value


