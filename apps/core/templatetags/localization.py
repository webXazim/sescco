def _normalize_proper_name(value):
    text = str(value or "").strip()
    # RTL rendering can make trailing punctuation appear before the name; normalize common cases.
    return text.strip().strip(" ،。")


@register.simple_tag
def proper_name(value, field_name=None):
    """Render company/client/contractor names as proper names, not translated meanings."""
    if field_name and not isinstance(value, str):
        source = getattr(value, field_name, "")
    else:
        source = value
    raw = str(source or "").strip()
    normalized = _normalize_proper_name(raw)
    lang = get_language() or "en"
    if lang == "en":
        return raw
    lang_map = PROPER_NAME_TRANSLITERATIONS.get(lang, {})
    if normalized in lang_map:
        return lang_map[normalized]
    # Fall back to static translations only when an exact proper-name rule exists there.
    static_map = STATIC_TRANSLATIONS.get(lang, {})
    if normalized in static_map:
        return static_map[normalized]
    # Chinese: preserve source names by default. Arabic: if no rule exists, preserve the source
    # rather than attempting a meaning translation.
    return raw

