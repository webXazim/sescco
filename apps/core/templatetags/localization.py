def static_text_id(text):
    return zlib.crc32(str(text).encode("utf-8"))


@register.simple_tag
def static_text(text):
    source_text = str(text)
    lang = get_language() or "en"
    object_id = static_text_id(source_text)
    override = LocalizedContent.objects.filter(
        content_type="statictext",
        object_id=object_id,
        language_code=lang,
        field_name="text",
    ).first()
    static_fallback = STATIC_TRANSLATIONS.get(lang, {}).get(source_text, source_text)
    if override and override.text and not _is_bad_demo_translation(override.text):
        override_text = str(override.text).strip()
        if lang != "en" and override_text == source_text.strip() and static_fallback != source_text:
            return mark_safe(static_fallback)
        return mark_safe(override.text)
    return static_fallback


